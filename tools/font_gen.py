#!/usr/bin/env python3
"""Compile the readable UKNC 8x11 font into MACRO-11 glyph data.

The resource is one block per character: a `char <octal code> <glyph>`
line, then eleven rows of '#' and '.'.  Codes run 040..177 octal, which
is ASCII punctuation and digits followed by Cyrillic in KOI-7 order -
the encoding used by the native game's Russian text, then firmware Latin
capitals in a separate bank for the splash credits, links and version.

Emits FONT, 11 bytes per glyph, with bit 0 as the leftmost pixel,
plus FONT_HEIGHT/FONT_FIRST/FONT_LAST.

    python3 tools/font_gen.py src/res/font8x11.txt --out build/font.mac
"""

import argparse
import os
import sys

HEIGHT = 11


def read_font(path):
    """Parse the resource.  A '#' only starts a comment OUTSIDE a glyph -
    inside one it is a lit pixel, and a row like '###.....' is data."""
    glyphs = {}
    code = None
    rows = []
    with open(path, encoding="utf-8") as fh:
        for lineno, raw in enumerate(fh, 1):
            s = raw.rstrip("\n").strip()
            if code is not None and len(rows) < HEIGHT:
                if not s:
                    continue
                if len(s) != 8 or set(s) - set("#."):
                    raise SystemExit(f"{path}:{lineno}: bad glyph row {s!r}")
                rows.append(s)
                if len(rows) == HEIGHT:
                    if code in glyphs:
                        raise SystemExit(f"{path}:{lineno}: duplicate glyph {code:03o}")
                    glyphs[code] = rows
                    code, rows = None, []
                continue
            if not s or s.startswith("#"):
                continue
            if s.lower().startswith("char"):
                code = int(s.split()[1], 8)
                rows = []
            else:
                raise SystemExit(f"{path}:{lineno}: expected a 'char' line, "
                                 f"got {s!r}")
    if code is not None:
        raise SystemExit(f"{path}: glyph {code:03o} is short")
    return glyphs


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("source")
    ap.add_argument("--out", required=True)
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args(argv)
    if os.path.exists(args.out) and not args.force:
        sys.exit(f"error: {args.out} exists (use --force)")

    glyphs = read_font(args.source)
    if not glyphs:
        sys.exit(f"error: no glyphs in {args.source}")
    first, last = min(glyphs), max(glyphs)
    if set(glyphs) != set(range(0o40, 0o200)):
        sys.exit("error: font must contain exactly codes 040..177")
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write("; Generated by tools/font_gen.py - do not edit.\n")
        fh.write(f"; Source: {args.source}\n\n")
        fh.write(f"FONT_FIRST = {first:o}\n")
        fh.write(f"FONT_LAST  = {last:o}\n\n")
        fh.write(f"FONT_HEIGHT = {HEIGHT}.\n\nFONT:\n")
        for code in range(first, last + 1):
            rows = glyphs[code]
            vals = []
            for r in rows:
                b = 0
                for x, ch in enumerate(r):
                    if ch == "#":
                        b |= 1 << x        # bit 0 = leftmost pixel
                vals.append(f"{b:o}")
            fh.write(f"\t\t.BYTE\t{', '.join(vals)}\t; {code:03o}\n")
    print(f"-> {args.out}: {len(glyphs)} glyphs, "
          f"{first:03o}..{last:03o}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
